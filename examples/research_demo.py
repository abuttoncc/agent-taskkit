#!/usr/bin/env python3
"""Run a complete financial research example using explicitly synthetic data."""
import argparse
import csv
from datetime import date
import json
from pathlib import Path
import sys

sys.dont_write_bytecode = True
SKILLS = Path(__file__).resolve().parents[1] / "skills"
sys.path.insert(0, str(SKILLS / "finance-research/scripts"))
import taskharness  # noqa: F401
from contract import write_new
import finance
import research


def run(root, scene="company"):
    research.new(root, "example-finance", "分析合成示例公司的收入增长与利润率；不使用真实证券数据。", scene)
    task = root / "projects/example-finance"
    today = date.today().isoformat()
    def save(name, data):
        (task / name).write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    raw = {"notice": "SYNTHETIC EXAMPLE, NOT A REAL COMPANY", "entity": "Example Co",
           "revenue_FY2024": "100", "revenue_FY2025": "125", "net_income_FY2025": "15", "unit": "CNY million"}
    save("inputs/source-example.json", raw)
    base = {"entity": "Example Co", "unit": "CNY million", "basis": "consolidated; restated series", "source_id": "S1"}
    save("inputs/metrics.json", {"schema_version": 1, "metrics": [
        {**base, "id": "rev-current", "period": "FY2025", "value": "125"},
        {**base, "id": "rev-previous", "period": "FY2024", "value": "100"},
        {**base, "id": "income-current", "period": "FY2025", "value": "15"}],
        "calculations": [
            {"id": "revenue-growth", "operation": "growth_pct", "inputs": ["rev-current", "rev-previous"], "comparability": "Two synthetic full years, same entity/unit/basis."},
            {"id": "net-margin", "operation": "percentage", "inputs": ["income-current", "rev-current"], "comparability": "Same synthetic reporting period and basis."}]})
    result = finance.calculate(task)
    write_new(task / "outputs/calculations-01.json", result)
    values = {x["id"]: x["value"] for x in result["results"]}
    with (task / "inputs/expected-v1.csv").open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(["id", "requirement", "description", "basis", "acceptance"])
        writer.writerow(["financial-summary", "required", "增长与利润率", "示例任务", "来源明确、计算可重算、报告包含边界"])
    (task / "deliverables").mkdir(exist_ok=True)
    (task / "deliverables/report-v1.md").write_text(f"""# Example Co 财务分析（合成示例）

本报告全部使用虚构数据，不是对真实公司的研究或投资判断。

信息截止日：{today}。金额单位：CNY million；口径：合并、重述后全年数据。
收入从 100 增至 125，按 (125 / 100 - 1) × 100 计算，同比 {values['revenue-growth']}%。
本期净利润 15，按 15 / 125 × 100 计算，净利润率 {values['net-margin']}%。

收入增加是本数据集的事实；没有现金流、分部、价格或竞争数据，不能据此判断增长质量或投资价值。
待验证问题：增长的量价来源、利润现金转化和一次性项目。

来源：[合成原始数据](../inputs/source-example.json)；[可复跑计算](../outputs/calculations-01.json)。
""", encoding="utf-8")
    (task / "findings.md").write_text(f"# 合成示例发现\n\n收入增长 {values['revenue-growth']}%，净利润率 {values['net-margin']}%。\n缺口：现金流、分部、估值、竞争数据；不外推真实公司。\n", encoding="utf-8")
    (task / "review.md").write_text("# 实查记录\n\n核对原始输入 100/125/15、单位与期间；计算器重算；报告标注合成数据并保留缺口。\n", encoding="utf-8")
    with (task / "request.md").open("a", encoding="utf-8") as handle:
        handle.write(f"\n本轮仅检验合成数据的追溯与重算链路，截止日 {today}；不扩展到实际投资结论。\n")
    (task / "sources.md").write_text("# 来源\n\nS1：inputs/source-example.json，完全合成的测试数据，来源为本仓库 examples/research_demo.py。\n", encoding="utf-8")
    save("inputs/research.json", {"schema_version": 1, "as_of": today,
        "sources": [{"id": "S1", "citation": "Synthetic Example Co data generated by research_demo.py", "locator": "revenue_FY2024, revenue_FY2025, net_income_FY2025", "published_at": today, "accessed_at": today, "evidence": ["inputs/source-example.json"]}],
        "claims": [{"id": "F1", "kind": "inference", "statement": f"收入增长 {values['revenue-growth']}%，净利润率 {values['net-margin']}%。", "source_ids": ["S1"], "calculation_ids": ["revenue-growth", "net-margin"], "reasoning": "使用同主体、单位与口径数据，分别计算增长率与利润率。"}],
        "calculation_files": ["outputs/calculations-01.json"],
        "review": [{"id": "financial-summary", "status": "PASS", "detail": "核对原始数据和两项公式，并检查报告中的合成数据标记和限制。", "evidence": ["inputs/source-example.json", "outputs/calculations-01.json", "deliverables/report-v1.md"]}],
        "deliverables": ["deliverables/report-v1.md"], "limitations": ["合成数据；本例验证工具链，不验证真实金融数据或投资结论。"]})
    report = research.check(task)
    write_new(task / "outputs/research-review-01.json", report)
    with (task / "README.md").open("a", encoding="utf-8") as handle:
        handle.write("\n示例完成：deliverables/report-v1.md；最近复核 outputs/research-review-01.json；仅验证合成数据工作流。\n")
    return {"task": str(task), "assessment": report["assessment"], "calculations": values, "synthetic": True}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True)
    args = parser.parse_args()
    print(json.dumps(run(args.root.resolve()), ensure_ascii=False, indent=2))
